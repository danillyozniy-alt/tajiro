/* ==========================================================================
   tajiro — Free Basic · появление по очереди

   Общая система появления на сайте ВЫКЛЮЧЕНА намеренно: js/core/reveal.js
   снимает крючки со всех блоков и выходит, потому что проявление при
   прокрутке читалось поломкой — блоки догружались на глазах. Решение общее
   и остаётся в силе; здесь появление вернулось точечно и ровно для двух
   мест, где движение работает смыслом, а не украшением:

     · шаги в 02 — у последовательности есть направление, и очередь его
       показывает;
     · опрос в панели конструктора в 04 — поля набираются одно за другим,
       то есть блок показывает ровно то, о чём говорит подпись под ним.

   Скрипт делает одно: помечает блок классом, когда тот входит в кадр.
   Всё остальное — в CSS.

   ПРОГРЕССИВНОЕ УЛУЧШЕНИЕ, как и в общей системе. Класс .is-armed ставит
   скрипт и только после двух проверок: движение разрешено и наблюдатель
   существует. Нет скрипта — нет класса — блок просто стоит на месте в
   своём обычном виде, скрытого состояния «по умолчанию» не существует.
   ========================================================================== */
(function () {
  'use strict';

  var blocks = document.querySelectorAll('[data-once]');
  if (!blocks.length) return;

  if (window.matchMedia &&
      window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  if (!('IntersectionObserver' in window)) return;

  /* Линия ниже края окна на 12%: блок успевает начать до того, как взгляд
     до него дойдёт. Отрицательный отступ снизу — тот же приём, что у
     наблюдателя в общей системе. */
  var io = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (!entry.isIntersecting) return;
      io.unobserve(entry.target);        /* один раз — и больше никогда */
      entry.target.classList.add('is-live');
    });
  }, { root: null, rootMargin: '0px 0px -12% 0px', threshold: 0 });

  Array.prototype.forEach.call(blocks, function (el) {
    el.classList.add('is-armed');
    io.observe(el);
  });
})();
