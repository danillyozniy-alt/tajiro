/* ==========================================================================
   tajiro — Free Basic · 02 · Очередь появления шагов

   Общая система появления на сайте ВЫКЛЮЧЕНА намеренно: js/core/reveal.js
   снимает крючки со всех блоков и выходит, потому что проявление при
   прокрутке читалось поломкой — блоки догружались на глазах. Решение общее
   и остаётся в силе; здесь появление вернулось точечно и ровно для трёх
   карточек одного блока.

   Почему им можно то, чего нельзя остальным: у последовательности есть
   направление, и очередь его показывает. Карточки едут одна за другой, а
   между ними прочерчивается связка — то есть движение здесь работает
   смыслом, а не украшением.

   ПРОГРЕССИВНОЕ УЛУЧШЕНИЕ, как и в общей системе. Класс .is-armed ставит
   скрипт и только после двух проверок: движение разрешено и наблюдатель
   существует. Нет скрипта — нет класса — карточки просто стоят на месте,
   скрытого состояния «по умолчанию» не существует.
   ========================================================================== */
(function () {
  'use strict';

  var list = document.querySelector('[data-steps]');
  if (!list) return;

  if (window.matchMedia &&
      window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  if (!('IntersectionObserver' in window)) return;

  list.classList.add('is-armed');

  /* Линия ниже края окна на 12%: блок успевает появиться до того, как
     взгляд до него дойдёт. Отрицательный отступ снизу — тот же приём, что
     у наблюдателя в общей системе. */
  var io = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (!entry.isIntersecting) return;
      io.unobserve(entry.target);        /* один раз — и больше никогда */
      entry.target.classList.add('is-live');
    });
  }, { root: null, rootMargin: '0px 0px -12% 0px', threshold: 0 });

  io.observe(list);
})();
